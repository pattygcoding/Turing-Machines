#!/usr/bin/env python3
"""Generate ``docs/links.md`` - every address the showcase answers.

The dashboard is a static bundle, so each implementation is addressable on its
own path (``/python``, ``/c``, ``/objectivec``), and the verified console capture
opens with ``?tab=output``, narrowed further with ``&scenario=<id>``.  This
script turns the showcase metadata into one copy-paste list of those addresses so
the list can never drift from the data the site is built from:

  * ``LANGUAGE_INFO`` in ``tools/generate_dashboard.py`` - the ``id`` (URL slug),
    display name, folder and category, and
  * ``SCENARIO_LABELS`` - the console captures the master test suite checks.

Usage::

    python tools/generate_link_index.py

Never hand-edit ``docs/links.md``; re-run this script instead.
"""

from __future__ import annotations

import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent

sys.path.insert(0, str(ROOT / "tools"))
from generate_dashboard import (  # noqa: E402  (needs the path above)
    DEFAULT_BRANCH,
    DEFAULT_REPOSITORY,
    LANGUAGE_INFO,
    SCENARIO_LABELS,
)

OUTPUT_FILE = ROOT / "docs" / "links.md"

# The published address, and the name it is shown under.
SITE = "https://turing.pattygcoding.com"
SITE_HOST = SITE.replace("https://", "")

# The project URL GitHub Pages serves alongside the custom domain.
MIRROR_HOST = "pattygcoding.github.io/Turing-Machines"

# The implementation the dashboard opens on (src/store/data.ts), used for the
# worked examples in the scenario section - every other id substitutes in.
REFERENCE_ID = "python"

# The console tab, which is the only tab that has to be named: the source tab is
# what an implementation opens on, so its address stays clean.
OUTPUT_QUERY = "?tab=output"


def _link(path: str) -> str:
    """A markdown link whose text is the address itself, so it copies cleanly."""
    return "[%s%s](%s%s)" % (SITE_HOST, path, SITE, path)


def _mirror_link(path: str) -> str:
    """The same link, through the GitHub Pages project URL."""
    return "[%s%s](https://%s%s)" % (MIRROR_HOST, path, MIRROR_HOST, path)


def _folder_link(meta: dict) -> str:
    """``<repository>/tree/<branch>/<folder>`` for one implementation."""
    folder = quote(meta["folder"], safe="/")
    return "%s/tree/%s/%s" % (DEFAULT_REPOSITORY.rstrip("/"), DEFAULT_BRANCH, folder)


def _language_rows() -> list[str]:
    rows = [
        "| Implementation | Tag | Category | Source | Console output |",
        "| --- | --- | --- | --- | --- |",
    ]
    for meta in LANGUAGE_INFO:
        rows.append(
            "| %s | `%s` | %s | %s | %s |"
            % (
                meta["name"],
                meta["extension"],
                meta["category"],
                _link("/" + meta["id"]),
                _link("/" + meta["id"] + OUTPUT_QUERY),
            )
        )
    return rows


def _scenario_rows() -> list[str]:
    """One row per capture.  The first is the tab's default, so it has no query."""
    rows = ["| Scenario | Link |", "| --- | --- |"]
    for index, (scenario, label) in enumerate(SCENARIO_LABELS.items()):
        suffix = "" if index == 0 else "&scenario=" + scenario
        rows.append(
            "| %s | %s |"
            % (label, _link("/%s%s%s" % (REFERENCE_ID, OUTPUT_QUERY, suffix)))
        )
    return rows


def _source_rows() -> list[str]:
    rows = ["| Implementation | Folder |", "| --- | --- |"]
    for meta in LANGUAGE_INFO:
        rows.append("| %s | [`%s`](%s) |" % (meta["name"], meta["folder"], _folder_link(meta)))
    return rows


def render() -> str:
    implementations = len(LANGUAGE_INFO)
    languages = len({meta.get("family", meta["id"]) for meta in LANGUAGE_INFO})
    repository = DEFAULT_REPOSITORY.replace("https://github.com/", "")

    lines = [
        "# Link index",
        "",
        "Every address the [Turing Machines Multi-Language Showcase](%s/) answers, in" % SITE,
        "copy-paste form. The dashboard is a static bundle, so each implementation is",
        "addressable on its own path (`/python`, `/c`, `/objectivec`) and the verified",
        "console capture opens with `?tab=output`, narrowed further with",
        "`&scenario=<id>`.",
        "",
        "Generated by [`tools/generate_link_index.py`](../tools/generate_link_index.py)",
        "from the same metadata the site is built from - re-run that script rather than",
        "editing this file.",
        "",
        "## The showcase",
        "",
        "| View | Link |",
        "| --- | --- |",
        "| Dashboard (opens `%s`) | %s |" % (REFERENCE_ID, _link("/")),
        "| Explicit entry document | %s |" % _link("/index.html"),
        "",
        "## Implementations",
        "",
        "All %d implementations across %d languages. The source column opens that" % (implementations, languages),
        "implementation in the dashboard; the console column opens the capture the",
        "master test suite checks it against.",
        "",
    ]
    lines.extend(_language_rows())
    lines.extend([
        "",
        "## Console output by scenario",
        "",
        "Nine captures, shared by every implementation - that is the whole point of the",
        "byte-for-byte protocol, so substituting any id for `%s` shows the same output." % REFERENCE_ID,
        "The first is what the console tab opens on; the rest are named explicitly.",
        "",
    ])
    lines.extend(_scenario_rows())
    lines.extend([
        "",
        "Any implementation and scenario combine, for example %s." % _link("/zig" + OUTPUT_QUERY + "&scenario=invalid"),
        "",
        "## Other shapes",
        "",
        "The same views are reachable without a pretty path - how the site behaves",
        "straight from disk, and how `public/404.html` forwards a deep link:",
        "",
        "| Shape | Link |",
        "| --- | --- |",
        "| Query string instead of a path (`?lang=`) | %s |" % _link("/index.html?lang=ruby"),
        "| Query string, console output | %s |" % _link("/index.html?lang=ruby&tab=output&scenario=empty"),
        "| Path tab, through the Pages project URL | %s |" % _mirror_link("/ruby/output?scenario=empty"),
        "",
        "Naming the tab on a path (`/ruby/output`) relies on the 404 shim, exactly as the",
        "host serves it: `public/404.html` answers the unknown path, forwards it as",
        "`index.html?lang=ruby&tab=output`, and the app writes the canonical",
        "`/ruby?tab=output&scenario=empty` back into the address bar. Both shapes open the",
        "same view, and the app normalises whichever one it was handed.",
        "",
        "## Source on GitHub",
        "",
        "[`%s`](%s/tree/%s) keeps one folder per implementation:" % (repository, DEFAULT_REPOSITORY, DEFAULT_BRANCH),
        "",
    ])
    lines.extend(_source_rows())
    lines.extend([
        "",
        "## Related sites",
        "",
        "* [%s](%s/) - this showcase." % (SITE_HOST, SITE),
        "* [connectfour.pattygcoding.com](https://connectfour.pattygcoding.com) - the",
        "  same idea for Connect Four, in the same set of languages.",
        "* [www.pattygcoding.com](https://www.pattygcoding.com) - the portfolio these",
        "  showcases belong to.",
        "",
    ])
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render())
    print(
        "Wrote %s (%d implementations, %d scenarios)"
        % (OUTPUT_FILE.relative_to(ROOT).as_posix(), len(LANGUAGE_INFO), len(SCENARIO_LABELS))
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
